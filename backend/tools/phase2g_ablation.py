"""Bounded predeclared reward experiment: six sequential full-joint learners."""
import argparse
import contextlib
import gc
import gzip
import hashlib
import json
from functools import partial
from pathlib import Path
import pickle
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'backend'))
OUT = ROOT/'backend/evaluations/phase2g'
C3 = ROOT/'backend/evaluations/phase2c3'
C2 = ROOT/'backend/evaluations/phase2c2'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, value):
    path.write_text(json.dumps(value, indent=2, allow_nan=False)+'\n')


def entries(pool):
    if pool not in ('training', 'validation'):
        raise ValueError('Only the prescribed development pools are authorized')
    data = json.loads((C2/f'{pool}_manifest.json').read_text())
    if data['pool'] != pool or len(data['entries']) != 18:
        raise ValueError('Unexpected development manifest')
    return data['entries']


def freeze():
    import torch
    from network_layer.joint_dqn_agent import JointDQNAgent, TrainingConfig
    from network_layer.reward_ablation import ARMS, VERSIONS, DEFINITIONS
    from tools.phase2c3_pilot import verify as verify_c3
    if (OUT/'protocol.json').exists():
        raise FileExistsError('Protocol already frozen')
    base = json.loads((C3/'protocol.json').read_text())
    verify_c3(base)
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip()
    base_commit = subprocess.check_output(['git', 'rev-parse', '2c8c438'], text=True).strip()
    if head != base_commit:
        raise ValueError('Freeze must start from the requested Phase 2F base')
    paths = {ROOT/n for n in base['input_sha256']}
    paths.update([C3/'protocol.json', ROOT/'backend/evaluations/phase2f/ABLATION_PLAN.md',
                  ROOT/'backend/notebooks/Resilient_data/embb_dl.csv'])
    paths.update((ROOT/'backend').rglob('*.py'))
    # Hash sources, not checkpoint/holdout data or generated bytecode.
    initializations = {}
    (OUT/'initializations').mkdir(exist_ok=True)
    for seed in base['network_seeds']:
        agent = JointDQNAgent(TrainingConfig(seed=seed, epsilon=base['exploration']['start'], **base['training_config']))
        path = OUT/'initializations'/f'seed{seed}.pt'
        torch.save(dict(policy=agent.policy.state_dict(), target=agent.target.state_dict(),
                        optimizer=agent.optimizer.state_dict(), rng_state=agent.rng.getstate()), path)
        initializations[str(seed)] = dict(path=str(path.relative_to(OUT)), sha256=digest(path),
            parameter_sha256=agent.fingerprint(), optimizer_empty=not agent.optimizer.state,
            rng_sha256=hashlib.sha256(pickle.dumps(agent.rng.getstate())).hexdigest())
        del agent
        gc.collect()
    p = dict(version='phase2g-reward-ablation-v1', base_commit='2c8c438', arms=list(ARMS),
        reward_versions=VERSIONS, fairness_definitions=DEFINITIONS,
        network_seeds=base['network_seeds'], initializations=initializations,
        episode_intervals=base['episode_intervals'], training_order=base['training_order'],
        checkpoint_after_episodes=base['checkpoint_after_episodes'],
        transitions_per_learner=base['transitions_per_learner'], training_config=base['training_config'],
        exploration=base['exploration'], rule_release_ratio=base['rule_release_ratio'],
        rule_release_decisions=base['rule_release_decisions'],
        aggregate_selection=base['aggregate_selection'], fairness_selection=base['fairness_selection'],
        allowed_pools=['training', 'validation'], validation_order=[e['id'] for e in entries('validation')],
        expected=dict(learners=6, training_episodes=54, checkpoints=18, validation_episodes=324,
                      optimizer_updates_per_learner=2660, paid_transitions_per_learner=2691),
        resources=base['resources'], input_sha256={str(f.relative_to(ROOT)):digest(f) for f in sorted(paths)},
        interpretation='Two NN seeds and two placements/regime; descriptive paired pilot only. No budget extension, extra arm, tuning or future holdout.')
    write(OUT/'protocol.json', p)


def verify(p):
    from network_layer.reward_ablation import ARMS, VERSIONS
    assert p['arms'] == list(ARMS) and p['reward_versions'] == VERSIONS
    assert p['transitions_per_learner'] == 2691 and p['checkpoint_after_episodes'] == [3, 6, 9]
    for name, expected in p['input_sha256'].items():
        if digest(ROOT/name) != expected:
            raise ValueError(f'Frozen input/source changed: {name}')
    for init in p['initializations'].values():
        assert digest(OUT/init['path']) == init['sha256']


def make_agent(seed, arm, p, agent_class=None):
    import torch
    from network_layer.joint_dqn_agent import TrainingConfig
    from network_layer.reward_ablation import RewardArmAgent
    agent = (agent_class or RewardArmAgent)(TrainingConfig(seed=seed, epsilon=p['exploration']['start'],
                                                        **p['training_config']), arm=arm)
    initial = p['initializations'][str(seed)]
    snapshot = torch.load(OUT/initial['path'], weights_only=True, map_location='cpu')
    agent.policy.load_state_dict(snapshot['policy'])
    agent.target.load_state_dict(snapshot['target'])
    agent.optimizer.load_state_dict(snapshot['optimizer'])
    agent.rng.setstate(snapshot['rng_state'])
    assert agent.fingerprint() == initial['parameter_sha256'] and not agent.optimizer.state
    assert hashlib.sha256(pickle.dumps(agent.rng.getstate())).hexdigest() == initial['rng_sha256']
    assert all(torch.equal(v, agent.target.state_dict()[k]) for k,v in agent.policy.state_dict().items())
    return agent


def run(entry, arm, agent, p, *, train=False, intervals=None, interval_sink=None):
    from tools.phase2c1_pilot import run_episode
    from tools.phase2c2_design import resolve_catalog
    from network_layer.reward_ablation import xAppRewardAblation
    rp = dict(p, training_scenario_seeds=[0,1,2], severities=[0,10,20], network_seed=agent.config.seed)
    with open('/dev/null', 'w') as quiet, contextlib.redirect_stdout(quiet):
        row = run_episode('A4', entry['severity'], entry['seed'], rp, agent=agent, train=train,
            intervals=intervals, catalog_override=resolve_catalog(C2, entry),
            app_class=partial(xAppRewardAblation, reward_arm=arm, interval_sink=interval_sink))
    row.update(scenario_id=entry['id'], regime=entry['regime'])
    return row


def check_gate(p):
    gate = json.loads((OUT/'correctness_gate.json').read_text())
    if not gate['passed'] or gate['protocol_sha256'] != digest(OUT/'protocol.json'):
        raise ValueError('Correctness gate missing, failed or stale')
    verify(p)


def execute(p):
    import torch
    from fractions import Fraction
    from network_layer.reward_ablation import RewardArmAgent
    from tools.phase2c1_pilot import assert_paired
    from tools.phase2c3_pilot import selection_key
    check_gate(p)
    if any((OUT/n).exists() for n in ('training.jsonl.gz', 'selection.json', 'updates.jsonl.gz')):
        raise FileExistsError('Refuse rerun or hidden budget extension')
    (OUT/'checkpoints').mkdir(exist_ok=True)
    training = {e['id']:e for e in entries('training')}
    validation = entries('validation')
    assert [e['id'] for e in validation] == p['validation_order']
    selected = []
    paired = []
    learner_checks = []
    with gzip.open(OUT/'training.jsonl.gz', 'wt') as tf, gzip.open(OUT/'validation.jsonl.gz', 'wt') as vf, \
         gzip.open(OUT/'updates.jsonl.gz', 'wt') as uf, gzip.open(OUT/'intervals.jsonl.gz', 'wt') as intf:
        def emit(stream, row):
            stream.write(json.dumps(row, allow_nan=False)+'\n')
        class LoggedAgent(RewardArmAgent):
            def learn(self):
                result = super().learn()
                if result is not None:
                    emit(uf, dict(reward_arm=arm, network_seed=seed, episode=episode,
                         optimizer_updates=self.updates, transitions=self.interactions, **self.last_update))
                return result
        # Each seed's three arms copy the same stored policy, target, optimizer and RNG.
        for seed in p['network_seeds']:
            for arm in p['arms']:
                verify(p)
                agent = make_agent(seed, arm, p, LoggedAgent)
                candidates = []
                def sink(record):
                    emit(intf, dict(reward_arm=arm, network_seed=seed, episode=episode,
                        training=is_training, scenario_id=sid, regime=entry['regime'],
                        severity=entry['severity'], **record))
                for episode,sid in enumerate(p['training_order'], 1):
                    entry = training[sid]
                    is_training = True
                    row = run(entry, arm, agent, p, train=True, interval_sink=sink)
                    row.update(episode=episode, total_transitions=agent.interactions)
                    emit(tf, row)
                    tf.flush();uf.flush();intf.flush()
                    print(json.dumps(dict(stage='training', arm=arm, seed=seed, episode=episode,
                        interactions=agent.interactions, updates=agent.updates, seconds=row['elapsed_seconds'])), flush=True)
                    if episode not in p['checkpoint_after_episodes']:
                        continue
                    path = Path('checkpoints')/f'{arm}_seed{seed}_ep{episode}.pt'
                    agent.save(OUT/path, run_metadata=dict(protocol_sha256=digest(OUT/'protocol.json'),
                        reward_arm=arm, ablation='A4', mask_version='matched-ablation-mask-v1',
                        episode=episode, interactions=agent.interactions, network_seed=seed))
                    frozen = (agent.fingerprint(), agent.rng.getstate(), agent.interactions, agent.updates,
                              hashlib.sha256(pickle.dumps(list(agent.replay))).hexdigest())
                    rows = []
                    is_training = False
                    for entry in validation:
                        sid = entry['id']
                        r = run(entry, arm, agent, p, interval_sink=sink)
                        r.update(candidate_episode=episode, total_transitions=agent.interactions)
                        emit(vf, r);vf.flush();intf.flush();rows.append(r)
                        paired.append({k:r[k] for k in ('scenario_seed','severity','deadline_assignment_sha256')} |
                                      {'physical':{'exogenous_sha256':r['physical']['exogenous_sha256']}})
                    after = (agent.fingerprint(), agent.rng.getstate(), agent.interactions, agent.updates,
                             hashlib.sha256(pickle.dumps(list(agent.replay))).hexdigest())
                    assert frozen == after, 'Validation mutated learner/replay/RNG'
                    candidates.append(dict(episode=episode, checkpoint=str(path),
                        aggregate_key=[str(x) for x in selection_key(rows,episode)],
                        fairness_key=[str(x) for x in selection_key(rows,episode,True)]))
                    print(json.dumps(dict(stage='validation', arm=arm, seed=seed, episode=episode,
                        aggregate_percent=float(selection_key(rows,episode)[0])*100,
                        worst_percent=float(selection_key(rows,episode)[1])*100)), flush=True)
                assert agent.interactions == 2691 and agent.updates == 2660
                chosen = {kind:min(candidates, key=lambda c:tuple(Fraction(x) for x in c[kind+'_key']))
                          for kind in ('aggregate','fairness')}
                selected.append(dict(reward_arm=arm, network_seed=seed, candidates=candidates, selected=chosen))
                write(OUT/'selection.json', selected)
                learner_checks.append(dict(reward_arm=arm, network_seed=seed, interactions=agent.interactions,
                    optimizer_updates=agent.updates, initial_parameter_sha256=p['initializations'][str(seed)]['parameter_sha256'],
                    final_parameter_sha256=agent.fingerprint(), validation_frozen=True))
                del agent
                gc.collect()
        assert_paired(paired)
        assert not torch.cuda.is_initialized()
    write(OUT/'training_checks.json', dict(learners=learner_checks, exogenous_pairing=True,
        cuda_initialized=False, validation_rows=len(paired), future_holdout_used=False))


def audit(p):
    import torch
    from network_layer.reward_ablation import RewardArmAgent
    from network_layer.joint_dqn_agent import TrainingConfig
    from tools.phase2c3_pilot import selection_key
    expected = {(arm,seed,ep) for arm in p['arms'] for seed in p['network_seeds'] for ep in [3,6,9]}
    fingerprints = {}
    for arm,seed,ep in sorted(expected):
        agent = RewardArmAgent(TrainingConfig(seed=seed, epsilon=1., **p['training_config']), arm=arm)
        agent.load(OUT/'checkpoints'/f'{arm}_seed{seed}_ep{ep}.pt')
        meta = agent.checkpoint_run_metadata
        assert meta['protocol_sha256'] == digest(OUT/'protocol.json')
        assert meta['reward_arm'] == arm and meta['interactions'] == ep*299
        assert agent.updates == ep*299-31
        fingerprints[arm,seed,ep] = agent.fingerprint()
        del agent
    with gzip.open(OUT/'validation.jsonl.gz','rt') as f:
        rows = [json.loads(line) for line in f]
    assert len(rows) == 324
    for r in rows:
        assert r['parameter_sha256'] == fingerprints[r['reward_arm'],r['network_seed'],r['candidate_episode']]
    # Check R0 against historical C3 only after measurement, never assume identity.
    with gzip.open(C3/'validation.jsonl.gz','rt') as f:
        old = {(r['network_seed'],r['candidate_episode'],r['scenario_id']):r for line in f
               if (r:=json.loads(line))['method']=='A4'}
    matches = []
    for r in rows:
        if r['reward_arm'] != 'R0':
            continue
        previous = old[r['network_seed'],r['candidate_episode'],r['scenario_id']]
        same = all(r[k] == previous[k] for k in ('control_digest','parameter_sha256','return_value'))
        same = same and r['physical']['per_ue'] == previous['physical']['per_ue']
        matches.append(same)
    write(OUT/'checkpoint_audit.json', dict(checkpoints_verified=len(fingerprints),
        validation_fingerprints_verified=len(rows), r0_historical_c3_comparisons=len(matches),
        r0_historical_controls_rewards_parameters_per_ue_all_match=all(matches),
        r0_historical_match_count=sum(matches), fresh_scenarios_executed=0,
        cuda_initialized=torch.cuda.is_initialized()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stage', choices=('freeze','run','audit'))
    args = parser.parse_args()
    from tools.phase2c1_pilot import configure_environment
    configure_environment()
    if args.stage == 'freeze':
        freeze()
        return
    p = json.loads((OUT/'protocol.json').read_text())
    verify(p)
    if args.stage == 'audit':
        audit(p)
        return
    started = time.perf_counter()
    execute(p)
    write(OUT/'runtime.json', dict(seconds=time.perf_counter()-started))


if __name__ == '__main__':
    main()
